import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../../core/utils/format.dart';
import '../../core/widgets/common_widgets.dart';
import '../../providers/app_providers.dart';
import '../../services/ai_insights.dart';

/// AI Insights: honest labeling of demo vs remote, graceful empty/error states.
class InsightsScreen extends ConsumerStatefulWidget {
  const InsightsScreen({super.key});

  @override
  ConsumerState<InsightsScreen> createState() => _InsightsScreenState();
}

class _InsightsScreenState extends ConsumerState<InsightsScreen> {
  late String _monthKey;
  Future<InsightResult>? _future;

  @override
  void initState() {
    super.initState();
    _monthKey = Format.currentMonthKey();
  }

  void _load() {
    final txs = ref.read(transactionsProvider).valueOrNull ?? [];
    final budgets = ref.read(budgetsProvider).valueOrNull ?? [];
    final currency = ref.read(settingsProvider).currency;
    _future = ref.read(aiServiceProvider).getInsights(
          transactions: txs,
          budgets: budgets,
          currencyCode: currency,
          monthKey: _monthKey,
        );
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final txAsync = ref.watch(transactionsProvider);
    final budgetsAsync = ref.watch(budgetsProvider);
    _load();

    return Scaffold(
      appBar: AppBar(title: const Text('AI Insights')),
      body: txAsync.when(
        loading: () => const LoadingView(message: 'Gathering insights…'),
        error: (e, _) => ErrorView(
          message: friendlyError(e),
          onRetry: () => ref.invalidate(transactionsProvider),
        ),
        data: (_) => FutureBuilder<InsightResult>(
          future: _future,
          builder: (context, snap) {
            if (snap.connectionState == ConnectionState.waiting) {
              return const LoadingView(
                  message: 'Analysing your spending…');
            }
            if (snap.hasError) {
              return ErrorView(
                message:
                    'Could not generate insights. ${friendlyError(snap.error!)}',
                onRetry: () => setState(() => _load()),
              );
            }
            final result = snap.data!;
            return ListView(
              padding: const EdgeInsets.all(16),
              children: [
                Row(
                  children: [
                    IconButton(
                      icon: const Icon(Icons.chevron_left_rounded),
                      onPressed: () {
                        final p = _monthKey.split('-');
                        final d = DateTime(int.parse(p[0]),
                            int.parse(p[1]) - 1, 1);
                        setState(() {
                          _monthKey = Format.monthKey(d);
                          _load();
                        });
                      },
                    ),
                    Expanded(
                      child: Center(
                        child: Text(Format.monthLabel(_monthKey),
                            style: theme.textTheme.titleMedium?.copyWith(
                                fontWeight: FontWeight.w700)),
                      ),
                    ),
                    IconButton(
                      icon: const Icon(Icons.chevron_right_rounded),
                      onPressed: () {
                        final p = _monthKey.split('-');
                        final d = DateTime(int.parse(p[0]),
                            int.parse(p[1]) + 1, 1);
                        setState(() {
                          _monthKey = Format.monthKey(d);
                          _load();
                        });
                      },
                    ),
                  ],
                ),
                Container(
                  padding: const EdgeInsets.all(12),
                  decoration: BoxDecoration(
                    color: result.isDemo
                        ? theme.colorScheme.secondaryContainer
                        : theme.colorScheme.primaryContainer,
                    borderRadius: BorderRadius.circular(12),
                  ),
                  child: Row(
                    children: [
                      Icon(
                          result.isDemo
                              ? Icons.phone_android_outlined
                              : Icons.cloud_outlined,
                          size: 20),
                      const SizedBox(width: 8),
                      Expanded(
                        child: Text(
                          result.isDemo
                              ? 'Demo insights · ${result.sourceLabel}. Connect an AI API key for real LLM insights (see README → AI configuration).'
                              : 'Generated by ${result.sourceLabel}.',
                          style: theme.textTheme.bodySmall,
                        ),
                      ),
                    ],
                  ),
                ),
                const SizedBox(height: 12),
                if (result.insights.isEmpty)
                  const EmptyState(
                    icon: Icons.auto_awesome_outlined,
                    title: 'Nothing to report',
                    subtitle:
                        'Add transactions to unlock personalised insights.',
                  )
                else
                  for (final i in result.insights)
                    Padding(
                      padding: const EdgeInsets.only(bottom: 10),
                      child: _InsightCard(insight: i),
                    ),
                const SizedBox(height: 8),
                Text(
                  'Budgets considered: ${budgetsAsync.valueOrNull?.where((b) => b.month == _monthKey).length ?? 0} · '
                  'Month: ${Format.monthLabel(_monthKey)}',
                  style: theme.textTheme.bodySmall?.copyWith(
                      color: theme.colorScheme.onSurfaceVariant),
                  textAlign: TextAlign.center,
                ),
                const SizedBox(height: 32),
              ],
            );
          },
        ),
      ),
    );
  }
}

class _InsightCard extends StatelessWidget {
  final AiInsight insight;
  const _InsightCard({required this.insight});

  (Color, Color, IconData) _style(BuildContext context, InsightTone tone) {
    final theme = Theme.of(context);
    switch (tone) {
      case InsightTone.good:
        return (
          Colors.green.shade700,
          Colors.green.withValues(alpha: 0.12),
          Icons.check_circle_outline
        );
      case InsightTone.warn:
        return (
          Colors.orange.shade800,
          Colors.orange.withValues(alpha: 0.12),
          Icons.warning_amber_outlined
        );
      case InsightTone.danger:
        return (
          theme.colorScheme.error,
          theme.colorScheme.errorContainer.withValues(alpha: 0.5),
          Icons.error_outline
        );
      case InsightTone.info:
        return (
          theme.colorScheme.primary,
          theme.colorScheme.primaryContainer.withValues(alpha: 0.5),
          Icons.lightbulb_outline
        );
    }
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final (accent, bg, icon) = _style(context, insight.tone);
    return AppCard(
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Container(
            padding: const EdgeInsets.all(10),
            decoration: BoxDecoration(
                color: bg, borderRadius: BorderRadius.circular(12)),
            child: Icon(icon, color: accent),
          ),
          const SizedBox(width: 12),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(insight.title,
                    style: theme.textTheme.titleSmall
                        ?.copyWith(fontWeight: FontWeight.w700)),
                const SizedBox(height: 4),
                Text(insight.body,
                    style: theme.textTheme.bodyMedium?.copyWith(
                        color: theme.colorScheme.onSurfaceVariant)),
              ],
            ),
          ),
        ],
      ),
    );
  }
}
